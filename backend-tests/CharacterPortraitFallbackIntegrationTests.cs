using Kufr.Backend.Features.Customers;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging.Abstractions;

internal static partial class AccountIdentityTests
{
    internal static async Task RunPortraitFallbackAsync()
    {
        var generated = new FallbackPortraitGenerator();
        var fallback = new FallbackPortraitLookup();
        await using var fixture = await Fixture.StartAsync(customerFeatures: true, configureServices: services =>
        {
            foreach (var descriptor in services.Where(x => x.ServiceType == typeof(IHostedService)
                && (x.ImplementationType == typeof(CharacterPortraitWorker)
                    || x.ImplementationType == typeof(CharacterEnrichmentWorker))).ToArray())
            {
                services.Remove(descriptor);
            }
        });
        using var owner = fixture.Client();
        using var key = new VirtualPasskey();
        await EnrollAsync(owner, key, Fixture.Bootstrap, "Portrait owner");
        var session = await CsrfAsync(owner);
        var account = session.GetProperty("account").GetProperty("id").GetString()!;
        var store = fixture.App.Services.GetRequiredService<CharacterProfileStore>();
        var worker = new CharacterPortraitWorker(fixture.App.Services.GetRequiredService<IServiceScopeFactory>(),
            store, generated, fallback, NullLogger<CharacterPortraitWorker>.Instance);
        var source = new CharacterPortraitSource("https://commons.wikimedia.org/wiki/File:Harry_Potter.jpg",
            "Harry Potter cosplay", "Example author", "CC BY-SA 4.0", "https://creativecommons.org/licenses/by-sa/4.0/");
        fallback.Result = new([1, 2, 3], source);

        async Task<CharacterPortraitJob> QueueAsync(string name)
        {
            var previous = await store.ReadAsync(account);
            await store.SaveAsync(account, new(previous?.Revision ?? 0, new(name, "Fiction"), previous?.ProfileId,
                OpenAiConsent: true, PortraitConsent: true));
            var research = (await store.ClaimAsync())!;
            var enrichment = new CharacterEnrichment(name, "Fiction", "A fictional traveler.", [], [], [], false,
                [], "offline", "test", 1, research.Revision, "synthetic");
            await store.CompleteAsync(research, enrichment, null);
            return store.ClaimPortrait()!;
        }

        var job = await QueueAsync("Harry Potter");
        await worker.ProcessAsync(job, CancellationToken.None);
        Check(fallback.Calls == 1 && store.ReadPortrait(account, job.ProfileId, job.Revision) is { Status: "ready", Source: not null },
            "failed generation publishes internet fallback with durable attribution");
        var view = await JsonAsync(await owner.GetAsync("/app/v1/prelaunch/character"));
        var artwork = view.GetProperty("artwork");
        Check(artwork.GetProperty("source").GetProperty("author").GetString() == source.Author,
            "authenticated view projects fallback attribution");
        var imageUrl = artwork.GetProperty("url").GetString()!;
        Check(imageUrl.StartsWith("/app/v1/prelaunch/character/portrait?")
            && (await owner.GetByteArrayAsync(imageUrl)).SequenceEqual(new byte[] { 1, 2, 3 }),
            "fallback bytes use existing authenticated same-origin portrait route");
        using var stranger = fixture.Client();
        Check(!(await stranger.GetAsync(imageUrl)).IsSuccessStatusCode, "fallback image remains private");

        generated.Fail = false;
        job = await QueueAsync("Raven");
        Check(store.ReadPortrait(account, job.ProfileId, job.Revision)?.Source is null, "new revision clears attribution");
        await worker.ProcessAsync(job, CancellationToken.None);
        Check(fallback.Calls == 1 && store.ReadPortrait(account, job.ProfileId, job.Revision) is { Status: "ready", Source: null },
            "successful generation skips internet and has no attribution");

        generated.Fail = true;
        fallback.Result = null;
        job = await QueueAsync("Absent character");
        await worker.ProcessAsync(job, CancellationToken.None);
        Check(store.ReadPortrait(account, job.ProfileId, job.Revision) is { Status: "failed", Source: null },
            "no internet match preserves failed portrait retry behavior");

        generated.Fail = false;
        generated.Image = [];
        job = await QueueAsync("Invalid generated image");
        await worker.ProcessAsync(job, CancellationToken.None);
        Check(store.ReadPortrait(account, job.ProfileId, job.Revision) is { Status: "failed" },
            "invalid generated bytes with no internet result finish as failed");
        generated.Fail = true;

        fallback.Result = new([4, 5], source);
        fallback.Started = new(TaskCreationOptions.RunContinuationsAsynchronously);
        fallback.Release = new(TaskCreationOptions.RunContinuationsAsynchronously);
        job = await QueueAsync("Late result");
        var processing = worker.ProcessAsync(job, CancellationToken.None);
        await fallback.Started.Task.WaitAsync(TimeSpan.FromSeconds(5));
        await store.DeleteAsync(account, job.Revision, job.ProfileId);
        fallback.Release.SetResult();
        await processing;
        Check(await store.ReadAsync(account) is null && store.ReadPortraitImage(account, job.ProfileId, job.Revision) is null,
            "late internet result cannot resurrect deleted profile");

        fallback.Started = null;
        fallback.Release = null;
        job = await QueueAsync("Canceled request");
        var calls = fallback.Calls;
        using var stopped = new CancellationTokenSource();
        stopped.Cancel();
        try { await worker.ProcessAsync(job, stopped.Token); }
        catch (OperationCanceledException) { }
        Check(fallback.Calls == calls, "worker shutdown never starts internet fallback");
    }

    private sealed class FallbackPortraitGenerator : ICharacterPortraitProvider
    {
        internal bool Fail { get; set; } = true;
        internal byte[] Image { get; set; } = [9, 8, 7];
        public Task<byte[]> GeneratePortraitAsync(CharacterPortraitJob job, CancellationToken token) => Fail
            ? Task.FromException<byte[]>(new InvalidOperationException("Offline generation failed."))
            : Task.FromResult(Image);
        public Task<string?> GenerateMessageAsync(CharacterUserInput input, CharacterEnrichment? enrichment,
            string creativePrompt, CancellationToken token) => Task.FromResult<string?>(null);
    }

    private sealed class FallbackPortraitLookup : ICharacterPortraitFallbackProvider
    {
        internal int Calls { get; private set; }
        internal CharacterPortraitFallback? Result { get; set; }
        internal TaskCompletionSource? Started { get; set; }
        internal TaskCompletionSource? Release { get; set; }
        public async Task<CharacterPortraitFallback?> FindAsync(CharacterPortraitJob job, CancellationToken token)
        {
            Calls++;
            Started?.TrySetResult();
            // Deliberately ignore cancellation to prove the durable completion fence.
            if (Release is not null) { await Release.Task; }
            return Result;
        }
    }
}

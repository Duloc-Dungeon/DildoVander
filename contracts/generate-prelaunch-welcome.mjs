import { readFile, writeFile } from 'node:fs/promises';

const schemaPath = new URL('./prelaunch-welcome.schema.json', import.meta.url);
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
if (schema.additionalProperties !== false || schema.required.join(',') !== 'joke,identity,teaser') {
  throw new Error('Prelaunch welcome contract must expose only its three public copy fields.');
}

const outputs = new Map([
  [new URL('../mobilni-aplikace/src/features/launch/generatedPrelaunchCharacter.ts', import.meta.url), `// Generated by contracts/generate-prelaunch-welcome.mjs. Do not edit by hand.\nexport interface PrelaunchWelcome {\n  joke: string;\n  identity: string;\n  teaser: string;\n}\n\nexport interface PrelaunchArtwork {\n  status: string;\n  loadingMessage?: string | null;\n  errorCode?: string | null;\n  finalMessage?: string | null;\n  welcome?: PrelaunchWelcome | null;\n  url?: string | null;\n}\n\nexport interface PrelaunchCharacterResponse {\n  character: { profileId: string; revision: number; name: string; universe: string; status: string } | null;\n  artwork: PrelaunchArtwork | null;\n}\n`],
  [new URL('./generated/prelaunch-welcome-validator.mjs', import.meta.url), `// Generated by contracts/generate-prelaunch-welcome.mjs. Do not edit by hand.\nimport Ajv from 'ajv';\nimport { readFile } from 'node:fs/promises';\n\nconst schema = JSON.parse(await readFile(new URL('../prelaunch-welcome.schema.json', import.meta.url), 'utf8'));\nconst validate = new Ajv({ allErrors: true, strict: true }).compile(schema);\nexport function validatePrelaunchWelcome(value) {\n  return validate(value) && value.joke.length + value.identity.length + value.teaser.length + 2 <= 250;\n}\n`]
]);

const checkOnly = process.argv.includes('--check');
let changed = false;
for (const [url, expected] of outputs) {
  let actual = '';
  try { actual = await readFile(url, 'utf8'); } catch { /* missing generated file */ }
  if (actual !== expected) {
    changed = true;
    if (!checkOnly) { await writeFile(url, expected, 'utf8'); }
  }
}
if (checkOnly && changed) { throw new Error('Generated prelaunch welcome contract drift; run npm run generate.'); }

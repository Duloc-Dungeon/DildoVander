import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import Ajv from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
const document = JSON.parse(await readFile(new URL('./game-openapi-v1.json', import.meta.url), 'utf8'));
const ingress = await readFile(new URL('../web/deploy/keepsake_proxy.py', import.meta.url), 'utf8');
assert.ok(ingress.includes('location ^~ /app/v1/ {'), 'account API proxy is required');
const ajv = new Ajv({ strict: true, allErrors: true }); addFormats(ajv);
for (const [name, schema] of Object.entries(document.components.schemas)) {
  ajv.addSchema(JSON.parse(JSON.stringify(schema).replaceAll('#/components/schemas/', 'urn:game:')), `urn:game:${name}`);
}
for (const name of Object.keys(document.components.schemas)) assert.ok(ajv.getSchema(`urn:game:${name}`));
for (const [path, methods] of Object.entries(document.paths)) for (const [method, operation] of Object.entries(methods)) {
  assert.deepEqual(operation.security, [{ AccountSession: [] }]);
  assert.match(path, /^\/app\/v1\/(?:game(?:\/|$)|admin\/game\/)/);
  assert.ok(operation['x-source'].startsWith('Features/Game/'));
  if (method === 'post') assert.ok(operation.parameters.some(parameter => parameter.name === 'X-DV-CSRF' && parameter.required));
}
const uuid = '11111111-1111-4111-8111-111111111111';
const command = ajv.getSchema('urn:game:GameCommand');
assert.ok(command({ operationId: uuid, expectedRevision: 1, choice: 'trick', sparkBid: 1 }));
assert.equal(command({ operationId: uuid, expectedRevision: 1, choice: 'trick', sparkBid: 2 }), false);
assert.equal(command({ operationId: uuid, expectedRevision: -1 }), false);
assert.equal(command({ operationId: uuid, expectedRevision: 1, choice: 'fireball' }), false);
assert.ok(command({ operationId: uuid, expectedRevision: 1, choice: 'protect' }));
const yolo = ajv.getSchema('urn:game:GameYoloView');
assert.ok(yolo({ status: 'choosing', beats: [], verdict: null, winnerId: null, errorCode: null, outcome: null, scenario: { id: 'tea-inspector-v1', title: 'Čaj pro kontrolora', objective: 'Čaj na stole.', situation: 'Okno je otevřené.', act: 1, ownChoiceLocked: true, opponentChoiceLocked: false, options: [], revealed: [] } }));
assert.ok(yolo({ status: 'complete', beats: [], verdict: 'Společné fiasko.', winnerId: null, errorCode: null, outcome: 'fiasco', scenario: null }));
assert.equal(yolo({ status: 'complete', beats: [], verdict: 'Hotovo.', winnerId: null, errorCode: null, outcome: 'technical-error' }), false);
const decision = ajv.getSchema('urn:game:GameYoloDecision');
const longestCard = { act: 1, choice: 'levitate', title: 'T'.repeat(100), benefit: 'B'.repeat(240), cost: 'C'.repeat(240) };
const longestReveal = `Plán: ${longestCard.title}. ${longestCard.benefit} ${longestCard.cost}`;
assert.equal(longestReveal.length, 589);
assert.ok(decision({ ...longestCard, consequence: longestReveal }), 'a valid generated card fits the revealed-decision contract');
assert.equal(decision({ ...longestCard, consequence: 'X'.repeat(641) }), false, 'the response contract remains bounded');
const team = ajv.getSchema('urn:game:GameTeamCreate');
assert.ok(team({ operationId: uuid, partnerId: 'one', opponentIds: ['two', 'three'] }));
assert.equal(team({ operationId: uuid, partnerId: 'one', opponentIds: ['two', 'two'] }), false);
const opponentWand = ajv.getSchema('urn:game:GameTeamOpponentWand');
const artworkUrl = `/app/v1/game/teams/${'1'.repeat(32)}/opponents/player-two/wand-artwork?revision=${'a'.repeat(64)}`;
assert.ok(opponentWand({ wandArtworkUrl: artworkUrl, wandName: 'Published wand', wandSynthetic: true }));
assert.equal(opponentWand({ wandArtworkUrl: 'https://example.invalid/private.png', wandName: 'Private', wandSynthetic: false }), false);
assert.equal(opponentWand({ wandArtworkUrl: artworkUrl.replace('a'.repeat(64), 'stale'), wandName: 'Stale', wandSynthetic: false }), false);
const teamArtwork = document.paths['/app/v1/game/teams/{id}/opponents/{opponentId}/wand-artwork'].get;
assert.ok(teamArtwork.parameters.some(parameter => parameter.in === 'query' && parameter.name === 'revision' && parameter.required));
assert.ok(teamArtwork.responses['200'].content['image/png']);
assert.equal(teamArtwork.responses['200'].headers['Cache-Control'].schema.const, 'no-store');
assert.equal(teamArtwork.responses['200'].headers['X-Content-Type-Options'].schema.const, 'nosniff');
const arcadeRanking = document.paths['/app/v1/game/arcade'].get;
const arcadeRankingSchema = ajv.compile(arcadeRanking.responses['200'].content['application/json'].schema);
assert.ok(arcadeRankingSchema({ rulesVersion: 'spark-v1', playerId: 'alice', groupId: 'group-a', best: 3,
  ranking: [{ id: 'alice', displayName: 'Alice', score: 3, rank: 1 }] }));
assert.ok(arcadeRankingSchema({ rulesVersion: 'spark-v2', playerId: 'alice', groupId: 'group-a', best: 3, ranking: [] }));
assert.equal(arcadeRankingSchema({ rulesVersion: 'spark-v3', playerId: 'alice', groupId: 'group-a', best: 3, ranking: [] }), false);
const arcadeIssue = document.paths['/app/v1/game/arcade/runs'].post;
const arcadeFinish = document.paths['/app/v1/game/arcade/runs/{runId}/finish'].post;
for (const operation of [arcadeIssue, arcadeFinish]) {
  assert.ok(operation.parameters.some(parameter => parameter.name === 'X-DV-CSRF' && parameter.in === 'header' && parameter.required));
}
const arcadeIssueRequestSchema = ajv.compile(arcadeIssue.requestBody.content['application/json'].schema);
assert.ok(arcadeIssueRequestSchema({ operationId: uuid }));
assert.ok(arcadeIssueRequestSchema({ operationId: uuid, rulesVersion: 'spark-v2' }));
assert.equal(arcadeIssueRequestSchema({ operationId: uuid, rulesVersion: 'spark-v3' }), false);
assert.equal(arcadeIssueRequestSchema({ operationId: 'short' }), false);
const arcadeTicketSchema = ajv.compile(arcadeIssue.responses['200'].content['application/json'].schema);
assert.ok(arcadeTicketSchema({ runId: 'a'.repeat(32), seed: 4294967295, rulesVersion: 'spark-v1', expiresAt: 7200000 }));
assert.ok(arcadeTicketSchema({ runId: 'a'.repeat(32), seed: 4294967295, rulesVersion: 'spark-v2', expiresAt: 7200000 }));
assert.equal(arcadeTicketSchema({ runId: 'a'.repeat(32), seed: 4294967296, rulesVersion: 'spark-v1', expiresAt: 7200000 }), false);
const arcadeReplaySchema = ajv.compile(arcadeFinish.requestBody.content['application/json'].schema);
assert.ok(arcadeReplaySchema({ endTick: 108000, taps: [0, 5, 10] }));
assert.equal(arcadeReplaySchema({ endTick: 108001, taps: [] }), false);
assert.equal(arcadeReplaySchema({ endTick: 10, taps: Array(24001).fill(0) }), false);
const arcadeReceiptSchema = ajv.compile(arcadeFinish.responses['200'].content['application/json'].schema);
assert.ok(arcadeReceiptSchema({ score: 3, best: 4, newBest: true }));
assert.equal(arcadeReceiptSchema({ score: 3, best: 4, newBest: 'yes' }), false);
assert.equal(arcadeFinish['x-max-request-bytes'], 512 * 1024);
assert.ok(arcadeFinish.responses['413']);
const boss = ajv.getSchema('urn:game:GameBossCommand');
assert.ok(boss({ operationId: uuid, expectedRevision: 1, choice: 'shield', sparkBid: 1 }));
assert.equal(boss({ operationId: 'not-a-guid', expectedRevision: 1 }), false);
const bossRickroll = ajv.getSchema('urn:game:GameBossRickrollCommand');
assert.ok(bossRickroll({ operationId: uuid, expectedRevision: 0, enabled: true }));
assert.equal(bossRickroll({ operationId: uuid, expectedRevision: -1, enabled: true }), false);
assert.equal(bossRickroll({ operationId: uuid, expectedRevision: 0, enabled: true, extra: true }), false);
const bossClaim = ajv.getSchema('urn:game:GameBossRickrollClaim');
assert.ok(bossClaim({ play: true }));
assert.equal(bossClaim({ play: 'true' }), false);
assert.deepEqual(document.paths['/app/v1/admin/game/groups/{id}/boss/rickroll'].post.responses['200'].content['application/json'].schema,
  { $ref: '#/components/schemas/GameBossProfile' });
assert.ok(document.paths['/app/v1/game/boss/rickroll/claim'].post.parameters.some(parameter => parameter.name === 'X-DV-CSRF' && parameter.required));
console.log('Mobile game OpenAPI: schemas, cookie/CSRF boundaries, account ingress and command bounds passed.');
